import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
test('conclusão de OP só ocorre pela Execução PCP transacional, nunca por atalhos de status', () => {
  const transitions = read('src/lib/pcp/orderTransitions.ts');
  const ordersHook = read('src/hooks/production/useProductionOrders.ts');
  const ordersTable = read('src/modules/production/productionOrders/OrdersTable.tsx');
  const queue = read('src/modules/production/ProductionQueue.tsx');
  const kanban = read('src/modules/production/kanban/hooks/useKanbanActions.ts');
  const terminal = read('src/modules/production/OperatorTerminal.tsx');
  assert.match(transitions, /next !== 'completed'/);
  assert.match(ordersHook, /canChangeOPStatus\(current\.status, updates\.status\)/);
  assert.match(ordersTable, /Concluir na execução/);
  assert.match(ordersTable, /onView\(order\)/);
  assert.doesNotMatch(queue, /update\(op\.id, \{ status: 'in_progress'/);
  assert.match(queue, /to="\/producao\/ordens"/);
  assert.match(kanban, /if \(newStatus === 'completed'\)/);
  assert.match(kanban, /Execução PCP da OP/);
  assert.doesNotMatch(terminal, /updates\.status = 'completed'/);
  assert.match(terminal, /recordProductionStepProgress/);
});
